# Generate System C / C2 set table (ADR-107): MAME segac2.cpp → src/c2/c2_games.h, src/c2/c2_prot.h
#   python tools/gen_c2_games.py [path to MAME segac2.cpp]
# Emits only ROM file names, offsets, lengths, CRCs, protection functions (EPM5032 equations, BSD-3 MAME code) and DIP defaults (no ROM data).
import os
import re
import sys

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
src_path = sys.argv[1] if len(sys.argv) > 1 else r'E:\Dev\Vita Port\ref\mame-src\src\mame\sega\segac2.cpp'
src = open(src_path, encoding='utf-8', errors='replace').read()
num = r'(0x[0-9a-fA-F]+|\d+)'

# ---- protection functions -> C ----
prot = {}
for m in re.finditer(r'^int (?:segac2_state|pclub_state)::prot_func_(\w+)\(int in\)\n\{\n(.*?)^\}', src, re.M | re.S):
    body = m.group(2).replace('int const', 'const int')
    prot[m.group(1)] = body
out = ['// Generated by tools/gen_c2_games.py (ADR-107). Source: prot_func_* in MAME src/mame/sega/segac2.cpp (BSD-3-Clause,',
       '// copyright-holders: David Haywood, Aaron Giles). EPM5032 protection chip: 4-bit output = f(prev write high 4 bits | prev read low 4 bits).',
       '#define C2BIT(x, n) (((x) >> (n)) & 1)', '']
for name, body in prot.items():
    out.append('static int c2prot_%s(int in)\n{\n%s}\n' % (name, body.replace('BIT(', 'C2BIT(')))
names = list(prot)
out.append('typedef int (*C2ProtFunc)(int in);')
out.append('static const C2ProtFunc c2prot_funcs[] = { %s };' % ', '.join('c2prot_' + n for n in names))
out.append('enum { %s };' % ', '.join('C2PROT_%s' % n.upper() for n in names))
open(os.path.join(root, 'src', 'c2', 'c2_prot.h'), 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')

# init_* -> protection + flags
init_prot = {}
for m in re.finditer(r'^void (?:segac2_state|pclub_state)::init_(\w+)\(\)\n\{\n(.*?)^\}', src, re.M | re.S):
    body = m.group(2)
    p = re.search(r'FUNC\((?:segac2_state|pclub_state)::prot_func_(\w+)\)', body)
    flags = []
    if 'init_noprot()' in body:
        p = p or re.match('', '')
        pname = 'dummy'
    else:
        pname = p.group(1) if p else 'dummy'
    if 'nop_write(0x800000' in body:
        flags.append('C2F_NOPROTW')
    if 'ichirjbl_prot_r' in body:
        flags.append('C2F_ICHIRJBL')
    if 'init_pclub()' in body:
        flags.append('C2F_PCLUB')
    init_prot[m.group(1)] = (pname, flags)

# ---- input ports: DSW default ----
ports = {}
for m in re.finditer(r'^static INPUT_PORTS_START\(\s*(\w+)\s*\)(.*?)^INPUT_PORTS_END', src, re.M | re.S):
    ports[m.group(1)] = m.group(2)


def dsw_default(name, port='DSW'):
    body = ports.get(name, '')
    val = None
    inc = re.search(r'PORT_INCLUDE\(\s*(\w+)\s*\)', body)
    if inc:
        val = dsw_default(inc.group(1), port)
    cur = None
    for line in body.split('\n'):
        line = line.split('//')[0].strip()
        r = re.match(r'PORT_(START|MODIFY)\(\s*"(\w+)"\s*\)', line)
        if r:
            cur = r.group(2)
            if cur == port and r.group(1) == 'START':
                val = 0xFF
            continue
        if cur != port:
            continue
        if val is None:
            val = 0xFF
        r = re.match(r'PORT_DIPNAME\(\s*' + num + r'\s*,\s*' + num, line)
        if r:
            mask, d = int(r.group(1), 0), int(r.group(2), 0)
            val = (val & ~mask) | (d & mask)
        r = re.match(r'PORT_DIPUNUSED\w*\(\s*' + num + r'\s*,\s*' + num, line)
        if r:
            mask, d = int(r.group(1), 0), int(r.group(2), 0)
            val = (val & ~mask) | (d & mask)
        r = re.match(r'PORT_SERVICE\w*\(\s*' + num + r'\s*,\s*IP_ACTIVE_LOW', line)
        if r:
            val |= int(r.group(1), 0)
    return 0xFF if val is None else val & 0xFF


# ---- ROMs ----
roms = {}
for m in re.finditer(r'^ROM_START\(\s*(\w+)\s*\)(.*?)^ROM_END', src, re.M | re.S):
    name, body = m.groups()
    lst, region = [], None
    for line in body.split('\n'):
        line = line.split('//')[0].strip()
        r = re.match(r'ROM_REGION\w*\(\s*' + num + r'\s*,\s*"([^"]+)"', line)
        if r:
            region = r.group(2)
            continue
        r = re.match(r'(ROM_LOAD16_BYTE|ROM_LOAD)\s*\(\s*"([^"]+)"\s*,\s*' + num + r'\s*,\s*' + num +
                     r'\s*,\s*(?:BAD_DUMP\s*)?CRC\(([0-9a-fA-F]+)\)', line)
        if r and region in ('maincpu', 'upd'):
            kind = 'C2_UPD' if region == 'upd' else ('C2_BYTE16' if r.group(1) == 'ROM_LOAD16_BYTE' else 'C2_PLAIN')
            lst.append((kind, r.group(2), int(r.group(3), 0), int(r.group(4), 0), int(r.group(5), 16)))
            continue
        r = re.match(r'ROM_COPY\(\s*"maincpu"\s*,\s*' + num + r'\s*,\s*' + num + r'\s*,\s*' + num, line)
        if r:
            lst.append(('C2_COPY', None, int(r.group(2), 0), int(r.group(3), 0), int(r.group(1), 0)))
            continue
        if line.startswith('ROM_') and line != 'ROM_END' and not line.startswith('ROM_REGION'):
            print('skip', name, line, file=sys.stderr)
    roms[name] = lst

gpat = r'^GAME\(\s*(\d+)\s*,\s*(\w+)\s*,\s*(\w+)\s*,\s*(\w+)\s*,\s*(\w+)\s*,\s*(\w+)\s*,\s*(\w+)\s*,\s*(\w+)\s*,\s*"((?:[^"\\]|\\.)*)"\s*,\s*"((?:[^"\\]|\\.)*)"'
out = ['// Generated by tools/gen_c2_games.py (ADR-107). Source: ROM_START, GAME, INPUT_PORTS in MAME src/mame/sega/segac2.cpp',
       '// (file names, offsets, lengths, CRCs and DIP defaults only, no ROM data).', '']
n = 0
maxr = 0
for m in re.finditer(gpat, src, re.M):
    year, set_, parent, machine, inp, cls, init, rot, maker, title = m.groups()
    if set_ not in roms:
        continue
    pname, flags = init_prot.get(init[5:], ('dummy', []))
    if machine == 'tfrceacjpb':
        flags = flags + ['C2F_DDR_F']
    if machine == 'ribbit':
        flags = flags + ['C2F_UPD_DELAY']
    is_c2 = 0 if machine == 'segac' else 1
    parent = None if parent == '0' else parent
    lst = roms[set_]
    maxr = max(maxr, len(lst))
    out.append('\t{ "%s", %s, "%s", %d, C2PROT_%s, %s, 0x%02x, {' % (
        set_, '"%s"' % parent if parent else 'NULL', title, is_c2, pname.upper(),
        ' | '.join(flags) if flags else '0', dsw_default(inp)))
    for k in lst:
        out.append('\t\t{ %s, %s, 0x%06x, 0x%06x, 0x%08x },' % (k[0], '"%s"' % k[1] if k[1] else 'NULL', k[2], k[3], k[4]))
    out.append('\t\t{ C2_END } } },')
    n += 1
open(os.path.join(root, 'src', 'c2', 'c2_games.h'), 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
print('games', n, 'max roms', maxr, 'prot', len(prot))
