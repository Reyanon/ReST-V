# Generate start screen game list header + ROM list doc (ADR-096, 098): GAME() entries in MAME drivers →
#   vita/src/frontend/stv_list.h (app start screen), docs/ROMLIST.md (ROM file names to install)
#   python tools/gen_stv_list.py [MAME source dir (stv.cpp, segac2.cpp)]
# Emits only names, makers, years and ROM set names (no ROM data). One tab per board: Sega System C, Sega System C2, Sega ST-V.
import os
import re
import sys

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
src_dir = sys.argv[1] if len(sys.argv) > 1 else r'E:\Dev\Vita Port\ref\mame'
order = ['Sega System C', 'Sega System C2', 'Sega ST-V']
# MAME machine per file → board. segac in segac2.cpp is System C, the rest (segac2 and variants) is System C2
files = [('segac2.cpp', lambda m: 'Sega System C' if m == 'segac' else 'Sega System C2'),
         ('stv.cpp', lambda m: 'Sega ST-V')]
ren = {'sandr': 'sandor'}  # loader / ROM file name (old MAME name)
bios = {'stvbios'}
pat = r'^GAME\(\s*(\d+)\s*,\s*(\w+)\s*,\s*(\w+)\s*,\s*(\w+)\s*,[^"]*"((?:[^"\\]|\\.)*)"\s*,\s*"((?:[^"\\]|\\.)*)"'
rows = []
for fname, board_of in files:
    src = open(os.path.join(src_dir, fname), encoding='utf-8', errors='replace').read()
    for m in re.finditer(pat, src, re.M):
        year, set_, parent, machine, maker, title = m.groups()
        if set_ in bios:
            continue
        set_ = ren.get(set_, set_)
        parent = ren.get(parent, parent)
        if parent in bios or parent == '0':
            parent = None
        board = board_of(machine)
        rows.append((order.index(board), title, set_, parent, year, maker, board))
rows.sort(key=lambda r: (r[0], r[1].lower()))

# sets the app can run (ROM definitions in src/core/stv.c)
stv_c = open(os.path.join(root, 'src', 'core', 'stv.c'), encoding='utf-8').read() + open(os.path.join(root, 'src', 'core', 'stv_games.h'), encoding='utf-8').read()
supported = set(re.findall(r'\{ \{ "(\w+)"', stv_c))
# ADR-107: System C / C2 sets (src/c2/c2_games.h)
supported |= set(re.findall(r'^	\{ "(\w+)"', open(os.path.join(root, 'src', 'c2', 'c2_games.h'), encoding='utf-8').read(), re.M))


def c(s):
    if s is None:
        return 'NULL'
    return '"' + s.replace(chr(92), chr(92) * 2).replace('"', chr(92) + '"') + '"'


out = ['// Start screen game list (ADR-096, 098). Source: GAME() entries in MAME src/mame/sega/segac2.cpp, stv.cpp (name, maker, year only,',
       '// no ROM data). Generated by tools/gen_stv_list.py. Sorted by board (tab), then title. Support is checked separately via STVFindGame.',
       '#ifndef RSTV_STV_LIST_H', '#define RSTV_STV_LIST_H', '',
       'typedef struct { const char *set, *parent, *year, *maker, *title, *board; } RstvListGame;',
       'static const RstvListGame s_stv_list[] = {']
for _, title, set_, parent, year, maker, board in rows:
    out.append('\t{ %s, %s, %s, %s, %s, %s },' % (c(set_), c(parent), c(year), c(maker), c(title), c(board)))
out += ['};', '#define RSTV_LIST_N ((int)(sizeof(s_stv_list) / sizeof(s_stv_list[0])))', '', '#endif', '']
open(os.path.join(root, 'vita', 'src', 'frontend', 'stv_list.h'), 'w', encoding='utf-8', newline='\n').write('\n'.join(out))


def md(s):
    return s.replace('|', '\\|')


doc = ['# ReST-V ROM list (by board)', '',
       '> Generated by `python tools/gen_stv_list.py` (game names and ROM set names from MAME `segac2.cpp`, `stv.cpp`). ROM files are not included.', '',
       '## Installing ROMs', '',
       '- Put ROM files **as zip, unextracted** in `ux0:data/restv/roms/`. File names must match the **ROM file** column below (MAME set names).',
       '- **Clones** (rows with a parent ROM) also need the parent zip. Example: `thuntk.zip` also needs `sandor.zip`.',
       '- **ST-V** games require the BIOS `stvbios.zip`.',
       '- ROM sets follow MAME. Other versions (different names or file layout) may not be recognized.',
       '- **Runs** column: ○ = runs in ReST-V, blank = no run table yet (shown bright on the start screen if the ROM is present, but selecting it shows a notice box). Games without ROMs are gray.', '']
for b in order:
    sub = [r for r in rows if r[6] == b]
    doc += ['## %s (%d)' % (b, len(sub)), '', '| Game | ROM file | Parent ROM | Year | Maker | Runs |', '|---|---|---|---|---|---|']
    for _, title, set_, parent, year, maker, board in sub:
        doc.append('| %s | `%s.zip` | %s | %s | %s | %s |' % (md(title), set_, '`%s.zip`' % parent if parent else '', year, md(maker),
                                                         '○' if set_ in supported else ''))
    doc.append('')
open(os.path.join(root, 'docs', 'ROMLIST.md'), 'w', encoding='utf-8', newline='\n').write('\n'.join(doc))
print(len(rows), 'games;', ', '.join('%s %d' % (b, sum(1 for r in rows if r[6] == b)) for b in order))
